#!/usr/bin/env node
// scripts/check-package-tasks.mjs — every workspace package must declare the gate tasks, or say
// out loud why it does not.
//
// `turbo run test` silently skips a package with no `test` script. Not a warning, not a
// non-zero exit — the task simply is not in the graph, and the run goes green having checked
// one package fewer than yesterday. That is how a monorepo loses coverage: not by a test
// failing, but by a package quietly stopping to have any.
//
// It is exactly what happened to the desktop packages. They carried lint and typecheck and no
// test, so the Electron main process — a URL-to-filesystem handler and the webPreferences that
// keep the renderer away from Node — was the one shipped surface with nothing asserting it, and
// nothing anywhere reported that.
//
// Exemptions are listed here, with reasons, rather than inferred. A package that should not run
// a task has to be written down, which is the difference between a decision and an omission.
import { execFileSync } from "node:child_process";
import { readFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

export const REQUIRED_TASKS = ["lint", "typecheck", "test"];

// name pattern -> { task: reason }. A package matching a pattern may omit those tasks.
export const EXEMPTIONS = [
  {
    match: /^@platform\/config$/,
    skip: {
      typecheck: "no TypeScript source — it ships .js/.cjs/.json config consumed by other packages",
      test: "declarative config only; its one piece of behaviour (the token bindings) is asserted by check-theme-tokens.mjs",
    },
  },
  {
    match: /-api-client$/,
    skip: {
      lint: "generated by hey-api and never hand-edited (CLAUDE.md); linting generated output produces findings nobody may act on",
      test: "generated from openapi.json — correctness is enforced by check-typegen-drift.mjs plus each consumer's typecheck",
    },
  },
];

/** The tasks `pkg` is allowed to omit, as { task: reason }. */
export function exemptionsFor(name) {
  return Object.assign({}, ...EXEMPTIONS.filter((e) => e.match.test(name)).map((e) => e.skip));
}

/** Tasks that are required for this package and absent from its scripts. */
export function missingTasks(name, scripts) {
  const exempt = exemptionsFor(name);
  return REQUIRED_TASKS.filter((task) => !scripts?.[task] && !exempt[task]);
}

// A declared task is not the same as a task that DOES something. `"test": "echo ok"` satisfies
// every "has a test script" check ever written while running nothing, and it is the natural shape
// of a script stubbed to unblock a build and never restored. So each task must also invoke a tool
// that can actually fail.
//
// Recognised tools per task. Adding one is a deliberate edit, which is the point: a package that
// starts running its tests through something new should have to say so.
export const TASK_TOOLS = {
  lint: [/\beslint\b/, /\bruff\b/],
  typecheck: [/\btsc\b/, /\bpyright\b/],
  test: [/\bjest\b/, /\bpytest\b/, /\bvitest\b/, /node\s+--test\b/],
};

/** Tasks whose script runs nothing that could fail. */
export function stubbedTasks(name, scripts) {
  const exempt = exemptionsFor(name);
  return REQUIRED_TASKS.filter((task) => {
    const script = scripts?.[task];
    if (!script || exempt[task]) return false;
    return !TASK_TOOLS[task].some((tool) => tool.test(script));
  });
}

/** Tasks a package declares that it was ALSO exempted from — a stale exemption. */
export function staleExemptions(name, scripts) {
  const exempt = exemptionsFor(name);
  return Object.keys(exempt).filter((task) => scripts?.[task]);
}

export function workspacePackages(root = ROOT) {
  return execFileSync("git", ["ls-files", "*/package.json"], { cwd: root, encoding: "utf8" })
    .split(/\r?\n/)
    .filter(Boolean)
    .filter((f) => !f.includes("node_modules/"))
    .map((file) => ({ file, ...JSON.parse(readFileSync(join(root, file), "utf8")) }))
    .filter((pkg) => typeof pkg.name === "string")
    .sort((a, b) => a.name.localeCompare(b.name));
}

function main() {
  const packages = workspacePackages();
  const problems = [];

  for (const pkg of packages) {
    for (const task of missingTasks(pkg.name, pkg.scripts)) {
      problems.push(
        `${pkg.name} (${pkg.file}) has no "${task}" script — turbo run ${task} skips it silently`,
      );
    }
    for (const task of stubbedTasks(pkg.name, pkg.scripts)) {
      problems.push(
        `${pkg.name} has a "${task}" script that runs no known tool: ${JSON.stringify(pkg.scripts[task])}`,
      );
    }
    // A package that grew the task it was excused from means the exemption is now a lie, and a
    // lie here is how the next omission gets waved through.
    for (const task of staleExemptions(pkg.name, pkg.scripts)) {
      problems.push(
        `${pkg.name} now HAS a "${task}" script — remove its exemption in ${"scripts/check-package-tasks.mjs"}`,
      );
    }
  }

  if (problems.length > 0) {
    console.error("");
    console.error("❌ Workspace packages are missing gate tasks:");
    for (const p of problems) console.error(`     ${p}`);
    console.error("");
    console.error(
      "   Add the script, or add a documented exemption in scripts/check-package-tasks.mjs.",
    );
    console.error("   An undeclared omission looks identical to a package that passes.");
    process.exit(1);
  }

  console.log(
    `check-package-tasks: ${packages.length} package(s) declare lint, typecheck and test`,
  );
}

// Guarded so importing this module (to test the rules) does not run the scan or exit the process.
if (
  process.argv[1] &&
  process.argv[1]
    .split(String.fromCharCode(92))
    .join("/")
    .endsWith("scripts/check-package-tasks.mjs")
) {
  if (!existsSync(join(ROOT, "package.json"))) process.exit(0);
  main();
}
